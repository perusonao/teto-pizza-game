/**
 * Train Kit: the three-line progress ledger (ingredients / recipes / cooking methods), measured, never typed.
 *
 *   shipped    = the REAL catalog modules, evaluated (`dump`), so a flag-gated row counts exactly as the build sees it
 *   staged     = the rows of src/data/staged/testSupport/*.ts, read as text (the staged catalog is never imported from outside)
 *   methods    = docs/reports/data/TETO_CONTENT-MASTER_methods.csv (its own generator stays the owner of that file)
 *   targets    = tools/train-kit/targets.json (the Owner's totals; the only authored numbers)
 *   landed     = src/trainKit/landed/*.json (which train shipped what)
 *
 * It does NOT replace the master ledger (docs/reports/TETO_CONTENT-MASTER_LEDGER_*): it runs that generator into a temp
 * directory and reports whether the committed ledger is stale, so the ledger is regenerated by its owner when it must be.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { ROOT, runner } from "./cli.mjs";

const stagedRows = (file) => readFileSync(join(ROOT, "src", "data", "staged", "testSupport", file), "utf8").split("\n").map((l) => l.trim()).filter((l) => l.startsWith("{")).map((l) => JSON.parse(l.replace(/,$/, "")));

/** Minimal CSV reader (quoted fields with commas / doubled quotes). */
export function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i += 1; } else if (ch === '"') quoted = false; else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; } else if (ch === "\n") { row.push(field); rows.push(row); row = []; field = ""; } else if (ch !== "\r") field += ch;
  }
  if (field !== "" || row.length > 0) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

export function summarize({ dump, stagedRecipes, stagedIngredients, methods, targets, landed }) {
  const shippedRecipes = new Set(dump.recipes.map((r) => r.id));
  const shippedIngredients = new Set(dump.ingredients.map((i) => i.id));
  const pendingRecipes = stagedRecipes.filter((r) => !shippedRecipes.has(r.id));
  const pendingIngredients = stagedIngredients.filter((i) => !shippedIngredients.has(i.id));
  const implemented = methods.filter((m) => m.status === "IMPLEMENTED").length;
  const line = (name, shipped, staged, target) => ({ line: name, shipped, staged, target, remaining: target - shipped, unplanned: target - shipped - staged, percent: Math.round((shipped / target) * 1000) / 10 });
  const byMechanic = {};
  for (const r of pendingRecipes) for (const m of r.mechanics?.length ? r.mechanics : ["(none: catalog-only)"]) byMechanic[m] = (byMechanic[m] ?? 0) + 1;
  return {
    lines: [line("ingredients", shippedIngredients.size, pendingIngredients.length, targets.ingredients), line("recipes", shippedRecipes.size, pendingRecipes.length, targets.recipes), line("methods", implemented, methods.length - implemented, targets.methods)],
    methodsByStatus: methods.reduce((acc, m) => ({ ...acc, [m.status]: (acc[m.status] ?? 0) + 1 }), {}),
    pendingRecipesByMechanic: Object.fromEntries(Object.entries(byMechanic).sort((a, b) => b[1] - a[1])),
    catalogOnlyReady: pendingRecipes.filter((r) => !r.mechanics?.length).map((r) => r.id).sort(),
    landedTrains: landed.map((k) => ({ tag: k.tag, train: k.train, recipes: k.recipes.length, ingredients: k.newIngredients.length })),
    notes: targets.notes ?? [],
  };
}

export function renderProgress(s, head) {
  const L = [`# Content progress (measured at \`${head}\`)`, "", "Generated by `node tools/train-kit/cli.mjs progress`; do not edit by hand. `unplanned` = target − shipped − staged (a slot with no staged row yet; negative = more staged rows than slots).", "", "| line | shipped | staged (not shipped) | target | remaining | unplanned | progress |", "|---|---:|---:|---:|---:|---:|---:|"];
  for (const l of s.lines) L.push(`| ${l.line} | ${l.shipped} | ${l.staged} | ${l.target} | ${l.remaining} | ${l.unplanned} | ${l.percent}% |`);
  L.push("", `Methods by status: ${Object.entries(s.methodsByStatus).map(([k, v]) => `${k} ${v}`).join(" / ")}.`, "", "Pending recipes by the mechanic they wait for (a recipe waiting for two is counted under both):", "");
  for (const [m, n] of Object.entries(s.pendingRecipesByMechanic)) L.push(`- ${m}: ${n}`);
  L.push("", `Catalog-only (no mechanic) and not shipped — the pool the next trains draw from (${s.catalogOnlyReady.length}): ${s.catalogOnlyReady.map((id) => `\`${id}\``).join(", ") || "none"}.`, "", `Landed through the train kit: ${s.landedTrains.map((t) => `${t.tag} (${t.recipes} recipe(s), ${t.ingredients} material(s))`).join(", ") || "none"}.`);
  if (s.notes.length) L.push("", ...s.notes.map((n) => `- ${n}`));
  if (s.masterLedger) L.push("", `Master ledger generator (run into a temp directory, nothing committed): ${s.masterLedger.failed.length === 0 ? "all checks PASS" : `**${s.masterLedger.failed.length} check(s) FAIL — the committed ledger is stale or its pinned totals need the owner's update**`}.`, ...s.masterLedger.failed.map((f) => `- ${f}`));
  return `${L.join("\n")}\n`;
}

export function progress(flags) {
  const work = mkdtempSync(join(tmpdir(), "train-kit-progress-"));
  if (!runner("dump", { TETO_KIT_OUT: join(work, "dump.json") }, ROOT, true)) return 2;
  const landedDir = join(ROOT, "src", "trainKit", "landed");
  const summary = summarize({
    dump: JSON.parse(readFileSync(join(work, "dump.json"), "utf8")),
    stagedRecipes: stagedRows("stagedRecipes.ts"),
    stagedIngredients: stagedRows("stagedIngredients.ts"),
    methods: parseCsv(readFileSync(join(ROOT, "docs", "reports", "data", "TETO_CONTENT-MASTER_methods.csv"), "utf8")),
    targets: JSON.parse(readFileSync(join(ROOT, "tools", "train-kit", "targets.json"), "utf8")),
    landed: existsSync(landedDir) ? readdirSync(landedDir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(landedDir, f), "utf8"))) : [],
  });
  const gen = join(ROOT, "docs", "reports", "data", "TETO_CONTENT-MASTER_gen.py.txt");
  if (existsSync(gen)) {
    const run = spawnSync("python3", ["-I", gen, ROOT, join(work, "ledger")], { encoding: "utf8" });
    summary.masterLedger = { failed: `${run.stdout}${run.stderr}`.split("\n").filter((l) => l.startsWith("FAIL")).map((l) => l.slice(5).trim()) };
  }
  const head = spawnSync("git", ["rev-parse", "--short", "HEAD"], { cwd: ROOT, encoding: "utf8" }).stdout.trim();
  const text = renderProgress(summary, head);
  if (typeof flags.out === "string") {
    mkdirSync(resolve(flags.out), { recursive: true });
    writeFileSync(join(resolve(flags.out), "progress.md"), text);
    writeFileSync(join(resolve(flags.out), "progress.json"), `${JSON.stringify({ head, ...summary }, null, 1)}\n`);
  }
  process.stdout.write(text);
  return 0;
}
