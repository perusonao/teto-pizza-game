/**
 * Train Kit: the follow-up sweep. A catalog train makes the same existing tests fail every time (totals, tail offsets, tables
 * keyed by recipe id, goldens). `pins` learns that list from the batches that already shipped; `sweep` runs exactly those files
 * (plus `tsc`) right after `apply`, so the follow-up worklist is known in minutes instead of one full-suite run per fix.
 * The sweep only REPORTS: every expectation is updated by a person / model who checks the new value is the approved one.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ROOT } from "./cli.mjs";

const PIN_FILE = join(ROOT, "tools", "train-kit", "pin-files.json");
const isPin = (f) => /\.test\.tsx?$/.test(f) || f.includes("__golden__");

/** `pins --commits a,b,c`: existing tests / goldens each batch commit had to MODIFY, with how many of the batches touched them. */
export function pins(flags) {
  if (typeof flags.commits !== "string") throw new Error("pins needs --commits <sha,sha,...> (the squash commits of shipped batches)");
  const commits = flags.commits.split(",");
  const count = new Map();
  for (const c of commits) {
    const run = spawnSync("git", ["show", "--name-status", "--format=", c], { cwd: ROOT, encoding: "utf8" });
    if (run.status !== 0) throw new Error(run.stderr);
    for (const line of run.stdout.split("\n")) {
      const [status, file] = line.split("\t");
      if (status === "M" && isPin(file)) count.set(file, (count.get(file) ?? 0) + 1);
    }
  }
  const files = [...count.entries()].filter(([f]) => existsSync(join(ROOT, f))).sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).map(([file, batches]) => ({ file, batches }));
  writeFileSync(PIN_FILE, `${JSON.stringify({ _comment: "Generated by `node tools/train-kit/cli.mjs pins`; do not edit by hand. Existing tests / goldens that shipped batches had to modify.", commits, files }, null, 1)}\n`);
  console.log(`${PIN_FILE}: ${files.length} file(s) from ${commits.length} batch commit(s); ${files.filter((f) => f.batches === commits.length).length} were touched by every batch.`);
  return 0;
}

/** `sweep [--min 2] [--no-tsc]`: tsc, then the pin tests touched by at least `--min` earlier batches. Exit 1 = there is follow-up work (listed). */
export function sweep(flags) {
  const { files, commits } = JSON.parse(readFileSync(PIN_FILE, "utf8"));
  const min = Number(flags.min ?? 2);
  const worklist = [];
  if (!flags["no-tsc"]) {
    const tsc = spawnSync("npx", ["tsc", "-b"], { cwd: ROOT, encoding: "utf8" });
    const typed = [...new Set((tsc.stdout ?? "").split("\n").map((l) => /^(\S+?)\(\d+,\d+\): error/.exec(l)?.[1]).filter(Boolean))];
    for (const f of typed) worklist.push(`TYPE   ${f}  (a table keyed by recipe / ingredient id needs the new row)`);
    console.log(`tsc: ${typed.length} file(s) with errors`);
  }
  const tests = files.filter((f) => f.batches >= min && /\.test\.tsx?$/.test(f.file) && existsSync(join(ROOT, f.file))).map((f) => f.file);
  const outFile = join(mkdtempSync(join(tmpdir(), "train-kit-sweep-")), "result.json");
  const run = spawnSync("npx", ["vitest", "run", "--reporter=json", `--outputFile=${outFile}`, ...tests], { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 28 });
  const json = (() => { try { return JSON.parse(readFileSync(outFile, "utf8")); } catch { return null; } })();
  if (!json) {
    process.stderr.write(`${run.stdout}\n${run.stderr}`);
    return 2;
  }
  for (const file of json.testResults.filter((r) => r.status !== "passed")) {
    const failed = file.assertionResults.filter((a) => a.status === "failed");
    worklist.push(`TEST   ${file.name.replace(`${ROOT}/`, "")}  (${failed.length} failing${failed[0] ? `, first: ${failed[0].title.slice(0, 90)}` : ""})`);
  }
  console.log(`pin sweep: ${tests.length} test file(s) that >= ${min} of ${commits.length} earlier batches had to modify; ${json.numFailedTests} failing test(s).`);
  for (const f of files.filter((x) => x.file.includes("__golden__") && x.batches >= min)) worklist.push(`GOLDEN ${f.file}  (regenerate with the suite's own update switch, then review the diff: insertions only)`);
  for (const w of worklist) console.log(w);
  return worklist.some((w) => !w.startsWith("GOLDEN")) ? 1 : 0;
}
